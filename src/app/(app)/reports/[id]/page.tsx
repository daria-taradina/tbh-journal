import { notFound } from "next/navigation";
import Container from "@/components/Container/Container";
import DeleteButton from "@/components/DeleteButton/DeleteButton";
import PageHeader from "@/components/PageHeader/PageHeader";
import ReportActions from "@/components/ReportActions/ReportActions";
import ReportView from "@/components/ReportView/ReportView";
import { deleteReport } from "@/lib/actions/reports";
import { reportTitle } from "@/lib/dates";
import { getReport } from "@/lib/queries";
import { reportToHtml, reportToText } from "@/lib/report-export";
import { normalizeReport } from "@/lib/report-schema";
import { requireSession } from "@/lib/session";

export default async function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  await requireSession();
  const id = Number((await params).id);
  const report = Number.isInteger(id) ? await getReport(id) : undefined;
  if (!report) notFound();

  const content = normalizeReport(report.content);
  const title = reportTitle(report.rangeStart, report.rangeEnd);

  return (
    <Container>
      <PageHeader title={title} />
      <ReportActions
        id={report.id}
        html={reportToHtml(title, content)}
        text={reportToText(title, content)}
      />
      <ReportView content={content} />
      <p style={{ color: "var(--muted)", fontSize: "0.85rem", marginTop: "1rem" }} data-print="hide">
        Generated by AI from your entries, so check it before you rely on it. It&apos;s a summary
        for session prep, not medical advice.
      </p>
      <DeleteButton
        action={deleteReport.bind(null, report.id)}
        confirmMessage="Delete this report? Your entries are not affected."
        label="Delete report"
      />
    </Container>
  );
}